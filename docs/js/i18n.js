  function readPrefs() {
    try {
      return JSON.parse(localStorage.getItem(KEY_PREFS) || "{}") || {};
    } catch (e) {
      return {};
    }
  }

  function writePrefs(next) {
    const prefs = Object.assign(readPrefs(), next);
    localStorage.setItem(KEY_PREFS, JSON.stringify(prefs));
    return prefs;
  }

  function detectSystemLang() {
    try {
      const list = []
        .concat(navigator.languages || [])
        .concat([navigator.language, navigator.userLanguage])
        .filter(Boolean);
      for (const raw of list) {
        const code = String(raw).toLowerCase().split("-")[0];
        if (SUPPORTED.includes(code)) return { lang: code, ok: true, raw: String(raw) };
      }
      return { lang: "it", ok: false, raw: list[0] || "" };
    } catch (e) {
      return { lang: "it", ok: false, raw: "" };
    }
  }

  function resolveLang(prefs) {
    const mode = prefs.langMode || "auto";
    if (mode === "it" || mode === "en") return mode;
    return detectSystemLang().lang;
  }

  function applyChrome(prefs) {
    const lang = resolveLang(prefs || readPrefs());
    const theme = (prefs || readPrefs()).theme === "light" ? "light" : "dark";
    document.documentElement.lang = lang;
    document.documentElement.setAttribute("data-theme", theme);
    return lang;
  }

  function t(key) {
    const lang = resolveLang(readPrefs());
    return (STR[lang] && STR[lang][key]) || (STR.it && STR.it[key]) || key;
  }

  function applyI18n() {
    const lang = applyChrome();
    const page = document.body && document.body.getAttribute("data-page");
    if (page) {
      const title = t("meta.title." + page);
      if (title && title !== "meta.title." + page) document.title = title;
    }
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    return lang;
  }

  try {
    applyChrome(readPrefs());
  } catch (e) {
    document.documentElement.lang = "it";
  }

  global.CpyI18n = {
    KEY_PREFS,
    STR,
    t,
    readPrefs,
    writePrefs,
    detectSystemLang,
    resolveLang,
    applyChrome,
    applyI18n,
  };
